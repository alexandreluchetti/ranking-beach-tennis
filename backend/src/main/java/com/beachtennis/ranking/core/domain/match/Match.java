package com.beachtennis.ranking.core.domain.match;

import com.beachtennis.ranking.core.domain.BusinessCalendar;
import com.beachtennis.ranking.core.exception.RuleViolationException;

import java.time.Instant;
import java.time.LocalDate;
import java.time.temporal.ChronoUnit;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * An independent, finished match between two teams of two. The id is generated by the client,
 * which makes registration idempotent.
 */
public record Match(
        UUID id,
        Instant playedAt,
        Score score,
        List<Participant> participants,
        MatchStatus status,
        UUID registeredBy,
        Instant registeredAt,
        Instant updatedAt) {

    private static final Comparator<Participant> POSITION_ORDER =
            Comparator.comparing(Participant::team).thenComparingInt(Participant::slot);

    public Match {
        Objects.requireNonNull(id, "id");
        Objects.requireNonNull(score, "score");
        Objects.requireNonNull(status, "status");
        Objects.requireNonNull(registeredBy, "registeredBy");
        Objects.requireNonNull(registeredAt, "registeredAt");
        Objects.requireNonNull(updatedAt, "updatedAt");
        if (playedAt == null) {
            throw new RuleViolationException("INVALID_MATCH_DATE");
        }
        // Whole seconds: stable across JSON and database precision, so resends compare equal.
        playedAt = playedAt.truncatedTo(ChronoUnit.SECONDS);
        participants = validatedParticipants(participants);
    }

    public MatchFormat format() {
        return score.format();
    }

    public Team winner() {
        return score.winner();
    }

    public boolean hasGuest() {
        return participants.stream().anyMatch(Participant::isGuest);
    }

    public List<Participant> team(Team team) {
        return participants.stream().filter(p -> p.team() == team).toList();
    }

    /** Business date of the match (Brasília), used to find its season. */
    public LocalDate playedOn() {
        return LocalDate.ofInstant(playedAt, BusinessCalendar.ZONE);
    }

    /**
     * Whether both matches have the same two teams, regardless of which side is A or B and of
     * slot order. Guests are compared by name (unnamed guests are all alike).
     */
    public boolean hasSameTeamsAs(Match other) {
        return teamsKey().equals(other.teamsKey());
    }

    /** Whether the user-provided content is identical (used for idempotent resends). */
    public boolean hasSameContentAs(Match other) {
        return playedAt.equals(other.playedAt)
                && score.equals(other.score)
                && participants.equals(other.participants);
    }

    /** Order-independent key of both teams: sorted list of sorted member keys. */
    private List<String> teamsKey() {
        return Stream.of(teamKey(Team.A), teamKey(Team.B)).sorted().toList();
    }

    private String teamKey(Team team) {
        return team(team).stream()
                .map(p -> p.isGuest()
                        ? "guest:" + Objects.requireNonNullElse(p.guestName(), "").toLowerCase(Locale.ROOT)
                        : "player:" + p.playerId())
                .sorted()
                .collect(Collectors.joining("|"));
    }

    private static List<Participant> validatedParticipants(List<Participant> participants) {
        if (participants == null || participants.size() != 4) {
            throw new RuleViolationException("INVALID_PARTICIPANTS");
        }
        Set<String> positions = new HashSet<>();
        Set<UUID> players = new HashSet<>();
        for (Participant p : participants) {
            if (!positions.add(p.team() + "-" + p.slot())) {
                throw new RuleViolationException("INVALID_PARTICIPANTS");
            }
            if (!p.isGuest() && !players.add(p.playerId())) {
                throw new RuleViolationException("DUPLICATE_PARTICIPANT");
            }
        }
        return participants.stream().sorted(POSITION_ORDER).toList();
    }
}
