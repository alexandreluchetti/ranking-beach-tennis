-- Matches store only what the user informed. Winner, guest presence, season and ranking points
-- are derived (decision D-007).
create table match (
    id                     uuid        primary key, -- generated by the client (idempotency)
    played_at              timestamptz not null,
    format                 varchar(10) not null,
    team_a_games           smallint    not null,
    team_b_games           smallint    not null,
    tiebreak_team_a_points smallint,
    tiebreak_team_b_points smallint,
    status                 varchar(10) not null,
    registered_by          uuid        not null references app_user (id),
    registered_at          timestamptz not null,
    updated_at             timestamptz not null,
    version                integer     not null default 0,
    constraint ck_match_format check (format in ('STANDARD', 'SHORT')),
    constraint ck_match_status check (status in ('VALID', 'VOIDED')),
    constraint ck_match_games check (team_a_games >= 0 and team_b_games >= 0 and team_a_games <> team_b_games),
    constraint ck_match_tiebreak check ((tiebreak_team_a_points is null) = (tiebreak_team_b_points is null))
);

create index ix_match_played_at on match (played_at);

create table match_participant (
    match_id   uuid        not null references match (id),
    team       char(1)     not null,
    slot       smallint    not null,
    player_id  uuid        references app_user (id), -- null for a guest
    guest_name varchar(40),
    primary key (match_id, team, slot),
    constraint ck_participant_team check (team in ('A', 'B')),
    constraint ck_participant_slot check (slot in (1, 2)),
    constraint ck_participant_guest check (player_id is null or guest_name is null)
);

create unique index ux_participant_player_per_match on match_participant (match_id, player_id)
    where player_id is not null;
create index ix_participant_player on match_participant (player_id);
